#!/bin/bash
# Regenerates THIRD-PARTY-NOTICES.md from the real dependencies of the pom (license-maven-plugin).
# Every dependency must have its license text in licenses/: if a new one arrives
# without it, the script stops. Run it when the dependencies change.
set -euo pipefail
cd "$(dirname "$0")"

./mvnw -q org.codehaus.mojo:license-maven-plugin:2.7.1:add-third-party \
    -Dlicense.excludedScopes=test,provided -Dlicense.outputDirectory=target/licenses -Dlicense.thirdPartyFilename=third-party.txt

# Version of an npm package copied by hand into terminal/: given by the package.json that Dependabot follows.
version() {
    sed -n "s|.*\"$1\": \"\([^\"]*\)\".*|\1|p" src/main/resources/lemuri/terminal/package.json
}

# The license text (in licenses/) for each artifact.
license_texts() {
    case "$1" in
        bcprov-*) echo "bouncycastle-LICENSE.txt" ;;
        dbus-java-*) echo "dbus-java-LICENSE.txt" ;;
        jsch) echo "jsch-LICENSE.txt, jsch-JZlib-LICENSE.txt, jsch-jBCrypt-LICENSE.txt" ;;
        gson|error_prone_annotations|annotations|kotlin-stdlib|jna-platform) echo "Apache-2.0.txt" ;;
        jna) echo "Apache-2.0.txt, jna-libffi-LICENSE.txt" ;;
        pty4j) echo "EPL-1.0.txt" ;;
        # Maven JARs do not have the legal/ folder of the SDK: the notices of the native libraries
        # (WebKit, ICU, libxml2, libxslt, GStreamer, GLib, libffi…) are in licenses/openjfx/.
        javafx-*) echo "GPL-2.0-only.txt, Classpath-exception-2.0.txt, openjfx/javafx.${1#javafx-}/" ;;
        slf4j-*) echo "slf4j-LICENSE.txt" ;;
        *) echo "" ;;
    esac
}

{
    echo "# Third-party notices"
    echo
    echo "<!-- Generated by licenses.sh from the dependencies in pom.xml: do not edit by hand. -->"
    echo
    echo "Lemuri includes the following components. Their license texts are in [licenses/](licenses/)."
    echo
    echo "| Component | Version | License | License text |"
    echo "|---|---|---|---|"
    echo "| [xterm.js](https://github.com/xtermjs/xterm.js) and addon-fit (bundled in \`src/main/resources/lemuri/terminal/\`) | $(version @xterm/xterm) / $(version @xterm/addon-fit) | MIT | xterm.js-LICENSE.txt |"
    grep -E '^ +\(' target/licenses/third-party.txt | sed -E 's/^ +//' | while read -r line; do
        licenses=$(echo "$line" | grep -oE '^(\([^)]*\) )+' | sed -E 's/\) \(/, /g; s/^\(//; s/\) $//')
        rest=${line#"$(echo "$line" | grep -oE '^(\([^)]*\) )+')"}
        name=${rest%% (*}
        coords=$(echo "$rest" | grep -oE '\([^ ]+:[^ ]+:[^ ]+ - [^)]*\)$' | tr -d '()')
        gav=${coords%% - *}
        url=${coords#* - }
        artifact=$(echo "$gav" | cut -d: -f2)
        version=$(echo "$gav" | cut -d: -f3)
        text=$(license_texts "$artifact")
        if [ -z "$text" ]; then
            echo "licenses.sh: no license text for $gav ($licenses): add it to licenses/ and to license_texts()" >&2
            exit 1
        fi
        # JNA has two licenses to choose from: Lemuri uses it under Apache-2.0.
        [ "$artifact" = jna ] || [ "$artifact" = jna-platform ] && licenses="Apache-2.0 (chosen; also available under LGPL-2.1-or-later)"
        echo "| [$name]($url) | $version | $licenses | $text |"
    done
    echo
    echo "The JavaFX jars include native libraries with their own notices, copied from the \`legal/\` folder of the OpenJFX SDK into [licenses/openjfx/](licenses/openjfx/): WebKit, ICU, libxml2 and libxslt in javafx-web; GStreamer, GLib and libffi in javafx-media; Mesa and the IJG JPEG library in javafx-graphics. The native part of JNA includes libffi (MIT)."
} > THIRD-PARTY-NOTICES.md.new
mv THIRD-PARTY-NOTICES.md.new THIRD-PARTY-NOTICES.md
echo "THIRD-PARTY-NOTICES.md updated"
