#!/bin/bash
# Regenerates THIRD-PARTY-NOTICES.md: the libraries the app and its backend link. They are the distribution's in the
# Linux package and are copied inside the Mac app. Every component must have its license text in licenses/: if one is
# missing, the script stops. Run it when a library is added or removed (CMakeLists.txt).
set -euo pipefail
cd "$(dirname "$0")"

# name | link | version | license | license texts (in licenses/)
components=(
    "Qt (Core, Gui, Widgets, Network)|https://www.qt.io|6|LGPL-3.0-only|LGPL-3.0.txt, GPL-3.0.txt"
    "libvterm|https://www.leonerd.org.uk/code/libvterm/|0.3|MIT|libvterm-LICENSE.txt"
    "libssh|https://www.libssh.org|0.10 or later|LGPL-2.1-or-later|LGPL-2.1.txt"
    "OpenSSL (libcrypto)|https://www.openssl.org|3|Apache-2.0|Apache-2.0.txt"
    "Argon2 reference implementation (libargon2)|https://github.com/P-H-C/phc-winner-argon2|20190702|Apache-2.0 (chosen; also available under CC0-1.0)|Apache-2.0.txt"
)

{
    echo "# Third-party notices"
    echo
    echo "<!-- Generated by licenses.sh: do not edit by hand. -->"
    echo
    echo "Lemuri (the app, lemuri, and its backend, lemuri-core) uses the following libraries, all linked"
    echo "dynamically: in the Linux package they are the distribution's own, in the Mac app they are copied into"
    echo "Contents/Frameworks. Their license texts are in [licenses/](licenses/)."
    echo
    echo "| Component | Version | License | License text |"
    echo "|---|---|---|---|"
    for c in "${components[@]}"; do
        IFS='|' read -r name url version license texts <<< "$c"
        for t in ${texts//,/ }; do
            [ -f "licenses/$t" ] || { echo "licenses.sh: licenses/$t is missing (for $name)" >&2; exit 1; }
        done
        echo "| [$name]($url) | $version | $license | $texts |"
    done
    echo
    echo "Qt and libssh are used under the LGPL: linked dynamically, they can be replaced by the user (in the Linux package"
    echo "they are the distribution's own; in the Mac app the libraries are in Contents/Frameworks)."
} > THIRD-PARTY-NOTICES.md.new
mv THIRD-PARTY-NOTICES.md.new THIRD-PARTY-NOTICES.md
# Every text in licenses/ belongs to a component: none left behind.
for f in licenses/*; do
    grep -q "$(basename "$f")" THIRD-PARTY-NOTICES.md || { echo "licenses.sh: $f is not used by any component" >&2; exit 1; }
done
echo "THIRD-PARTY-NOTICES.md updated"
